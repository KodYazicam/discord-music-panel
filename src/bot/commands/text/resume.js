/**
 * Resume Command - Resume paused playback
 */

const { EmbedBuilder } = require('discord.js');

module.exports = {
    name: 'resume',
    aliases: ['devam', 'unpause', 'continue'],
    description: 'Resume the paused track',
    usage: '',
    cooldown: 2,

    async execute(message, args, bot) {
        const voiceChannel = message.member?.voice?.channel;
        if (!voiceChannel) {
            return message.reply({
                embeds: [
                    new EmbedBuilder()
                        .setColor(0xED4245)
                        .setDescription('❌ You must be in a voice channel!')
                ]
            });
        }

        const result = bot.resume(message.guild.id);

        if (result.success) {
            return message.reply({
                embeds: [
                    new EmbedBuilder()
                        .setColor(0x57F287)
                        .setDescription('▶️ Resumed the music')
                ]
            });
        } else {
            return message.reply({
                embeds: [
                    new EmbedBuilder()
                        .setColor(0xED4245)
                        .setDescription(`❌ ${result.message}`)
                ]
            });
        }
    }
};
